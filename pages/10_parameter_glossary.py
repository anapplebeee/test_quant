# ========== 策略参数 ==========
st.subheader("策略参数 (Strategy)")

st.markdown("""
| 参数名 | 含义 | 计算方法 | 常用范围 | 当前值 |
|--------|------|----------|----------|--------|
| `lookback_days` | 动量回看天数 | 计算收益率的时间窗口 | 20-252天 | 60 |
| `top_k` | 持仓股票数 | 每期持有的股票数量 | 5-50只 | 10 |
| `rebalance_days` | 调仓周期 | 相邻两次再平衡的间隔 | 1-20天 | 5 |
| `max_weight_pct` | 单股最大权重 | 单只股票在组合中的最大占比 | 5%-20% | 15% |
| `min_avg_amount` | 流动性门槛 | 20日平均成交额最低要求 | 1000万-1亿 | 5000万 |
| `liquidity_days` | 流动性计算窗口 | 计算日均成交额的天数 | 20-60天 | 20 |
| `use_regime_filter` | 是否启用市场环境过滤 | 根据基准均线判断牛熊 | true/false | true |
| `regime_filter_days` | 市场环境均线天数 | 判断市场状态的移动平均 | 20-250天 | 20 |
""")

with st.expander("📌 详细说明"):
    st.markdown("""
    **lookback_days (动量回看)**
    - 定义：计算个股过去N日收益率作为动量得分
    - 原理：过去涨的股票未来继续涨（动量效应）
    - 经验：A股60日动量较稳定，太短（<20日）噪声大，太长（>120日）反应迟钝

    **top_k (持仓数量)**
    - 定义：每期持有的股票数量
    - 原理：分散化降低个股风险
    - 经验：10-20只足够分散非系统风险；太少集中度高，太多管理成本高

    **rebalance_days (调仓周期)**
    - 定义：多久调整一次持仓
    - 原理：平衡交易成本与因子时效性
    - 经验：5个交易日（一周）是常见选择；太短交易成本高，太长因子衰减

    **max_weight_pct (单股最大权重)**
    - 定义：单只股票在组合中的最大占比
    - 原理：控制个股集中度风险
    - 经验：10%-15%是常见上限；超过20%个股暴雷影响过大

    **min_avg_amount (流动性门槛)**
    - 定义：股票20日平均成交额的最低要求
    - 原理：确保能实际买卖（有足够对手盘）
    - 经验：A股量化通常要求日均成交额 > 3000万-1亿

    **use_regime_filter (市场环境过滤)**
    - 定义：根据基准指数（如沪深300）是否在均线上方判断市场状态
    - 原理：熊市时动量策略容易失效，空仓避险
    - 经验：能显著降低最大回撤，但可能错过反弹初期
    """)

st.divider()

# ========== 风控参数 ==========
st.subheader("风控参数 (Risk)")

st.markdown("""
| 参数名 | 含义 | 计算方法 | 常用范围 | 当前值 |
|--------|------|----------|----------|--------|
| `max_position_pct` | 单股最大持仓权重 | 个股市值 / 组合总市值 | 10%-30% | 25% |
| `max_daily_loss_pct` | 单日最大亏损限制 | 日亏损超过阈值触发止损 | 3%-10% | 5% |
""")

with st.expander("📌 详细说明"):
    st.markdown("""
    **max_position_pct (单股最大持仓权重)**
    - 定义：单只股票在组合中的最大允许占比
    - 原理：防止个股过度集中导致的非系统性风险
    - 经验：25%是常见上限；公募基金"双十原则"要求单股≤10%

    **max_daily_loss_pct (单日止损线)**
    - 定义：单日亏损超过该比例时触发风控措施
    - 原理：防止极端行情下的重大损失
    - 经验：5%是常见设置；过紧（<3%）容易被震荡触发，过松（>10%）保护不足
    """)

st.divider()

# ========== 回测参数 ==========
st.subheader("回测参数 (Backtest)")

st.markdown("""
| 参数名 | 含义 | 计算方法 | 常用范围 | 当前值 |
|--------|------|----------|----------|--------|
| `initial_cash` | 初始资金 | 回测起始资金 | 10万-1000万 | 100万 |
| `commission_rate` | 佣金率 | 券商收取的交易佣金 | 0.01%-0.05% | 0.025% |
| `commission_min` | 最低佣金 | 单笔最低收费 | 5元 | 5元 |
| `stamp_tax_rate` | 印花税 | 卖出时收取 | 0.05% | 0.05% |
| `transfer_fee_rate` | 过户费 | 沪市股票收取 | 0.001% | 0.001% |
| `slippage_rate` | 滑点率 | 执行价格与信号价的偏差 | 0.05%-0.2% | 0.1% |
| `min_order_value` | 最小订单金额 | 低于该金额不交易 | 1000元 | 1000元 |
""")

with st.expander("📌 详细说明"):
    st.markdown("""
    **commission_rate (佣金率)**
    - 定义：券商按交易金额收取的佣金比例
    - 注意：量化交易通常能拿到万2.5以下的费率
    - 影响：高频策略中佣金是主要成本，不可忽略

    **stamp_tax率 (印花税)**
    - 定义：卖出股票时国家收取的税费
    - 注意：仅卖出收取，买入不收
    - 影响：对换手率高的策略影响显著

    **slippage_rate (滑点)**
    - 定义：实际成交价与预期价格的偏差
    - 来源：市场冲击成本 + 下单延迟
    - 经验：A股量化通常假设0.1%滑点；大资金或流动性差的股票需更高

    **为什么交易成本很重要？**
    - 一个年化换手率200%的策略，每年买卖金额 = 2×组合总值
    - 单次往返成本 ≈ 0.025%×2 + 0.05% + 0.1%×2 = 0.25%
    - 年化交易成本 ≈ 200% × 0.25% = 0.5%
    - 如果策略年化超额收益只有3%，交易成本吃掉1/6！
    """)

st.divider()

# ========== 绩效指标 ==========
st.subheader("绩效指标 (Performance Metrics)")

st.markdown("""
| 指标 | 含义 | 计算公式 | 优秀标准 |
|------|------|----------|----------|
| **累计收益** | 整个回测期的总收益率 | (终值/初值 - 1) | 越高越好 |
| **CAGR** | 年化复合收益率 | (终值/初值)^(1/年数) - 1 | > 15% |
| **夏普比率 (Sharpe)** | 风险调整后收益 | (年化收益 - 无风险利率) / 年化波动率 | > 1.0 |
| **最大回撤 (MaxDD)** | 峰值到谷底最大亏损 | max((峰值-谷值)/峰值) | < -20% |
| **卡玛比率 (Calmar)** | 收益与最大回撤比 | CAGR / |MaxDD| | > 1.0 |
| **日胜率** | 盈利交易日占比 | 盈利天数 / 总天数 | > 50% |
| **超额收益** | 超越基准的收益 | 策略CAGR - 基准CAGR | > 0 |
""")

with st.expander("📌 详细说明"):
    st.markdown("""
    **夏普比率 (Sharpe Ratio)**
    - 含义：每承担一单位风险获得的超额收益
    - 解读：Sharpe=1.0 表示每承担10%波动获得10%超额收益
    - 注意：假设收益正态分布，对尾部风险不敏感

    **最大回撤 (Maximum Drawdown)**
    - 含义：从任意高点到后续最低点的最大跌幅
    - 解读：MaxDD=-30% 意味着最坏情况亏损30%
    - 重要性：回撤50%需要涨100%才能回本！

    **卡玛比率 (Calmar Ratio)**
    - 含义：年化收益与最大回撤的比值
    - 解读：Calmar=1.0 表示年化收益能覆盖最大回撤
    - 优势：比夏普更关注最坏情况

    **为什么不能只看收益？**
    - 策略A：年化30%，最大回撤40% → 卡玛=0.75
    - 策略B：年化20%，最大回撤10% → 卡玛=2.0
    - 策略B更优：因为投资者往往在低点赎回，实际体验更差
    """)

st.divider()

# ========== 因子指标 ==========
st.subheader("因子指标 (Factor Metrics)")

st.markdown("""
| 指标 | 含义 | 计算公式 | 有效标准 |
|------|------|----------|----------|
| **IC (Information Coefficient)** | 因子与未来收益的相关性 | 因子值与未来收益的Spearman相关 | \\|IC\\| > 0.03 |
| **ICIR (IC Information Ratio)** | IC的风险调整值 | mean(IC) / std(IC) | \\|ICIR\\| > 0.5 |
| **IC正率** | IC为正的比例 | IC > 0 的月份数 / 总月份数 | > 55% |
| **多空收益** | 头部-尾部组合收益差 | 多头组收益 - 空头组收益 | > 0 |
| **因子换手率** | 头部/尾部股票变更比例 | 新进入/退出的股票数 / 总数 | 适中 |
""")

with st.expander("📌 详细说明"):
    st.markdown("""
    **IC (Information Coefficient)**
    - 含义：因子值与未来收益的秩相关系数
    - 范围：[-1, 1]，绝对值越大预测力越强
    - 经验：A股中\|IC\|>0.05的因子已经算优秀

    **ICIR (IC Information Ratio)**
    - 含义：IC的均值除以标准差，衡量IC稳定性
    - 解读：ICIR>0.5 表示因子稳定有效；ICIR<0.3 不稳定
    - 重要性：高IC但低ICIR的因子不可靠（可能某几个月贡献）

    **多空收益 (Long-Short Return)**
    - 含义：买入因子值最高的10%股票，卖出最低的10%
    - 用途：验证因子能否产生实际可交易的收益
    - 注意：需扣除交易成本后仍为正才有价值

    **因子换手率 (Turnover)**
    - 含义：每期头部/尾部组合中股票变更的比例
    - 影响：换手率越高，交易成本越大
    - 权衡：高IC因子如果换手率太高，净收益可能不如低IC低换手因子
    """)

st.divider()

# ========== 风险指标 ==========
st.subheader("风险指标 (Risk Metrics)")

st.markdown("""
| 指标 | 含义 | 计算公式 | 安全范围 |
|------|------|----------|----------|
| **VaR (Value at Risk)** | 置信度下的最大亏损 | 收益分布的5%分位数 | 越小越好 |
| **CVaR (Conditional VaR)** | 尾部期望亏损 | 低于VaR的平均收益 | 越小越好 |
| **HHI (Herfindahl)** | 持仓集中度 | Σ(权重²) | < 0.1 |
| **有效持仓数** | 等效等权持仓数 | 1 / HHI | > 10 |
| **跟踪误差** | 相对基准的波动 | std(策略收益 - 基准收益) | 视目标而定 |
| **信息比率 (IR)** | 超额收益 / 跟踪误差 | 超额年化 / 年化跟踪误差 | > 0.5 |
""")

with st.expander("📌 详细说明"):
    st.markdown("""
    **VaR (Value at Risk)**
    - 含义：95%置信度下，一天内最大亏损不会超过该值
    - 解读：日VaR=-2% → 95%概率日亏损不超过2%
    - 局限：不告诉你剩下5%的极端情况

    **CVaR / Expected Shortfall**
    - 含义：当亏损超过VaR时，平均会亏多少
    - 解读：比VaR更关注尾部风险
    - 用途：巴塞尔协议III推荐使用CVaR

    **HHI (Herfindahl-Hirschman Index)**
    - 含义：衡量持仓集中度的经典指标
    - 计算：各股权重的平方和
    - 解读：等权10只 → HHI=0.1；等权20只 → HHI=0.05；单只100% → HHI=1.0

    **信息比率 (Information Ratio)**
    - 含义：每单位主动风险带来的超额收益
    - 解读：IR>0.5 为优秀，IR>1.0 为顶尖
    - 用途：衡量基金经理的选股能力
    """)

st.divider()

